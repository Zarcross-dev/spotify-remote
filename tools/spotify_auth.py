#!/usr/bin/env python3
"""
Spotify Remote overlay - PC login helper.

Logs in to Spotify once and writes the config.ini the Switch overlay needs
(client_id, client_secret, refresh_token). Python 3.8+, standard library only.

    python3 spotify_auth.py                      # asks for client id/secret, writes ./config.ini
    python3 spotify_auth.py --sd /media/SWITCH   # write straight to a mounted SD card
    python3 spotify_auth.py --ftp 192.168.1.42   # upload to the Switch over FTP (ftpd / sys-ftpd)

Before running: create an app at https://developer.spotify.com/dashboard and add
the Redirect URI  http://127.0.0.1:8888/callback
"""

import argparse
import base64
import ftplib
import getpass
import http.server
import io
import json
import os
import secrets
import sys
import threading
import urllib.error
import urllib.parse
import urllib.request
import webbrowser

REDIRECT_URI = "http://127.0.0.1:8888/callback"
SCOPES = (
    "user-read-playback-state user-modify-playback-state user-read-currently-playing "
    "playlist-read-private playlist-read-collaborative "
    "user-library-read user-library-modify"
)
SWITCH_CONFIG_PATH = "/switch/spotify-remote/config.ini"


def read_ini(path):
    values = {}
    try:
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line or line[0] in "#;[" or "=" not in line:
                    continue
                key, val = line.split("=", 1)
                values[key.strip()] = val.strip().strip("\"'")
    except FileNotFoundError:
        pass
    return values


def render_ini(cfg):
    return (
        "; Spotify Remote overlay configuration\n"
        "; Generated by tools/spotify_auth.py\n"
        "[spotify]\n"
        f"client_id={cfg['client_id']}\n"
        f"client_secret={cfg['client_secret']}\n"
        f"refresh_token={cfg['refresh_token']}\n"
        f"device_id={cfg.get('device_id', '')}\n"
        f"poll_interval_ms={cfg.get('poll_interval_ms', '2000')}\n"
        f"ssl_verify={cfg.get('ssl_verify', '1')}\n"
        f"debug_log={cfg.get('debug_log', '0')}\n"
    )


def exchange_code(client_id, client_secret, code):
    body = urllib.parse.urlencode({
        "grant_type": "authorization_code",
        "code": code,
        "redirect_uri": REDIRECT_URI,
    }).encode()
    auth = base64.b64encode(f"{client_id}:{client_secret}".encode()).decode()
    req = urllib.request.Request(
        "https://accounts.spotify.com/api/token",
        data=body,
        headers={
            "Authorization": f"Basic {auth}",
            "Content-Type": "application/x-www-form-urlencoded",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=20) as resp:
            data = json.load(resp)
    except urllib.error.HTTPError as e:
        try:
            err = json.load(e)
            msg = err.get("error_description") or err.get("error") or str(e)
        except Exception:
            msg = str(e)
        sys.exit(f"Token exchange failed: {msg}")
    if "refresh_token" not in data:
        sys.exit("Spotify did not return a refresh token.")
    return data


def wait_for_callback(auth_url, state, open_browser):
    """Serve http://127.0.0.1:8888/callback and return the authorization code."""
    result = {}
    done = threading.Event()

    class Handler(http.server.BaseHTTPRequestHandler):
        def do_GET(self):
            parsed = urllib.parse.urlparse(self.path)
            if parsed.path != "/callback":
                self.send_error(404)
                return
            params = urllib.parse.parse_qs(parsed.query)
            result["code"] = params.get("code", [""])[0]
            result["state"] = params.get("state", [""])[0]
            result["error"] = params.get("error", [""])[0]
            ok = result["code"] and not result["error"]
            page = ("<h2>Spotify Remote: login complete.</h2><p>You can close this tab.</p>" if ok
                    else f"<h2>Login failed: {result['error'] or 'no code'}</h2>")
            body = page.encode()
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
            done.set()

        def log_message(self, *args):
            pass

    try:
        server = http.server.HTTPServer(("127.0.0.1", 8888), Handler)
    except OSError:
        return None  # port in use -> caller falls back to manual paste

    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()

    print("\nOpen this URL to log in (it should open automatically):\n")
    print(auth_url + "\n")
    if open_browser:
        webbrowser.open(auth_url)
    print("Waiting for Spotify to redirect back... (Ctrl+C to cancel)")

    try:
        while not done.wait(0.5):
            pass
    except KeyboardInterrupt:
        server.shutdown()
        sys.exit("\nCancelled.")
    server.shutdown()

    if result.get("error"):
        sys.exit(f"Spotify returned an error: {result['error']}")
    if result.get("state") != state:
        sys.exit("State mismatch - please try again.")
    return result.get("code")


def manual_code(auth_url, state):
    print("\nOpen this URL in any browser and log in:\n")
    print(auth_url + "\n")
    print("You'll end up on a page that doesn't load (http://127.0.0.1:8888/callback?code=...).")
    pasted = input("Paste that full address here: ").strip()
    query = urllib.parse.urlparse(pasted).query or pasted
    params = urllib.parse.parse_qs(query)
    if params.get("error"):
        sys.exit(f"Spotify returned an error: {params['error'][0]}")
    if params.get("state", [""])[0] != state:
        sys.exit("State mismatch - copy the address from the newest login attempt.")
    code = params.get("code", [""])[0]
    if not code:
        sys.exit("No code found in that address.")
    return code


def upload_ftp(target, user, password, content):
    host, _, port = target.partition(":")
    port = int(port or 5000)
    print(f"Uploading to ftp://{host}:{port}{SWITCH_CONFIG_PATH} ...")
    with ftplib.FTP() as ftp:
        ftp.connect(host, port, timeout=15)
        ftp.login(user, password)
        for part in ("switch", "spotify-remote"):
            try:
                ftp.cwd(part)
            except ftplib.error_perm:
                ftp.mkd(part)
                ftp.cwd(part)
        ftp.storbinary("STOR config.ini", io.BytesIO(content.encode()))
    print("Uploaded.")


def write_private(path, content):
    """Write config.ini readable only by the current user (it holds the client secret)."""
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


def main():
    ap = argparse.ArgumentParser(description="Link the Spotify Remote Switch overlay to your Spotify account.")
    ap.add_argument("--client-id")
    ap.add_argument("--client-secret")
    ap.add_argument("--config", help="existing config.ini to read client id/secret from")
    ap.add_argument("--out", default="config.ini", help="where to write config.ini (default: ./config.ini)")
    ap.add_argument("--sd", help="SD card root; writes <sd>/switch/spotify-remote/config.ini")
    ap.add_argument("--ftp", metavar="HOST[:PORT]", help="upload to the Switch over FTP (default port 5000)")
    ap.add_argument("--ftp-user", default="anonymous")
    ap.add_argument("--ftp-pass", default="")
    ap.add_argument("--manual", action="store_true", help="don't run a local server; paste the redirect URL instead")
    ap.add_argument("--no-browser", action="store_true", help="don't open the browser automatically")
    args = ap.parse_args()

    existing = read_ini(args.config) if args.config else {}
    if args.sd and not existing:
        existing = read_ini(os.path.join(args.sd, SWITCH_CONFIG_PATH.lstrip("/")))

    client_id = args.client_id or existing.get("client_id") or input("Spotify Client ID: ").strip()
    client_secret = (args.client_secret or existing.get("client_secret")
                     or getpass.getpass("Spotify Client Secret (hidden): ").strip())
    if not client_id or not client_secret:
        sys.exit("Client ID and Client Secret are required.")

    state = secrets.token_hex(16)
    auth_url = "https://accounts.spotify.com/authorize?" + urllib.parse.urlencode({
        "response_type": "code",
        "client_id": client_id,
        "redirect_uri": REDIRECT_URI,
        "scope": SCOPES,
        "state": state,
        "show_dialog": "true",
    })

    code = None if args.manual else wait_for_callback(auth_url, state, not args.no_browser)
    if not code:
        if not args.manual:
            print("Port 8888 is busy, falling back to manual mode.")
        code = manual_code(auth_url, state)

    tokens = exchange_code(client_id, client_secret, code)
    cfg = dict(existing)
    cfg.update(client_id=client_id, client_secret=client_secret, refresh_token=tokens["refresh_token"])
    content = render_ini(cfg)

    wrote = False
    if args.sd:
        path = os.path.join(args.sd, SWITCH_CONFIG_PATH.lstrip("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        write_private(path, content)
        print(f"Wrote {path}")
        wrote = True
    if args.ftp:
        upload_ftp(args.ftp, args.ftp_user, args.ftp_pass, content)
        wrote = True
    if not wrote or args.out != "config.ini":
        write_private(args.out, content)
        print(f"Wrote {os.path.abspath(args.out)}")
        print(f"Copy it to the SD card as  {SWITCH_CONFIG_PATH}")

    print("\nDone! Open the overlay on your Switch (or choose 'Reload config.ini').")


if __name__ == "__main__":
    main()
